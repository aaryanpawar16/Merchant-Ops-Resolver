// Re-captures the real data behind the landing page figures and writes lib/sampleRun.ts.
// Start the app first (npm run dev), then: npm run sample:capture
// Tip: start it with a dummy NEATLOGS_API_KEY and NEATLOGS_ENDPOINT=http://127.0.0.1:9 so the capture
// runs do not show up in your real neatlogs project.
import fs from "node:fs";
import path from "node:path";

const base = process.env.APP_URL ?? "http://localhost:3000";
const instruction = "Sharma Kirana's settlement for txn #48213 failed. Investigate and resolve.";
const out = path.join(process.cwd(), "lib", "sampleRun.ts");

async function capture(chaos) {
  const res = await fetch(`${base}/api/runs`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ instruction, chaos, llm: false, speed: 1 }),
  });
  if (!res.ok) throw new Error(`The app answered ${res.status}. Is it running at ${base}?`);
  const reader = res.body.getReader();
  const decoder = new TextDecoder();
  let seen = "";
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    seen += decoder.decode(value, { stream: true });
  }
  const id = seen.match(/"id":"(run_[0-9a-f]+)"/)?.[1];
  return (await fetch(`${base}/api/runs/${id}`)).json();
}

const fmt = (ms) => (ms < 1000 ? `${Math.round(ms)} ms` : `${(ms / 1000).toFixed(1)} s`);
const finalSpans = (run) => {
  const map = new Map();
  for (const e of run.events) if (e.type === "span.start" || e.type === "span.end") map.set(e.span.id, e.span);
  return [...map.values()];
};
const result = (run) => run.events.find((e) => e.type === "run.end").result;

const plain = await capture(false);
const chaos = await capture(true);

// Trace waterfall and checkpoint chain come from the run with the forced timeout.
const spans = finalSpans(chaos);
const byId = new Map(spans.map((s) => [s.id, s]));
const depth = (s) => (s.parentId && byId.has(s.parentId) ? 1 + depth(byId.get(s.parentId)) : 0);
const kindOf = (s) => (s.status === "error" ? "retry" : s.kind === "decision" ? "decision" : s.kind);
const trace = spans
  .filter((s) => s.kind !== "checkpoint")
  .sort((a, b) => a.startMs - b.startMs || depth(a) - depth(b))
  .map((s) => {
    const ms = (s.endMs ?? s.startMs) - s.startMs;
    return { kind: kindOf(s), name: s.name, depth: depth(s), start: s.startMs, ms, label: fmt(ms) };
  });
const resumedFrom = chaos.events.map((e) => (e.type === "log" ? e.text.match(/resumed from (ckpt_\w+)/) : null)).find(Boolean)?.[1] ?? null;
const memoryLine = chaos.events.find((e) => e.type === "log" && /^Memory hit/.test(e.text))?.text ?? null;
const checkpoints = chaos.events
  .filter((e) => e.type === "checkpoint")
  .map((e) => ({ id: e.checkpoint.id, label: e.checkpoint.label, agent: e.checkpoint.agent, hash: e.checkpoint.hash.slice(0, 12), parent: e.checkpoint.parentId }));

// Step timings for the case scene come from the run without the forced timeout.
const ps = finalSpans(plain);
const find = (name) => ps.find((s) => s.name === name);
const dur = (s) => (s.endMs ?? s.startMs) - s.startMs;
const ckAt = (label) => plain.events.find((e) => e.type === "checkpoint" && e.checkpoint.label === label).checkpoint.atMs;
const timings = {
  received: fmt(dur(ps.find((s) => s.name === "get_settlement"))),
  planned: `3 workers, ${fmt(ckAt("plan"))}`,
  investigated: `memory hit, ${fmt(dur(find("investigation.run")))}`,
  applied: fmt(ckAt("retrigger") - find("resolution.run").startMs),
  verified: `status=SETTLED, ${fmt(dur(find("resolution.verify")))}`,
  closed: `KB updated, ${fmt(dur(find("closure.run")))}`,
  traced: `${result(plain).spanCount} spans`,
};

const body = `// Generated by scripts/capture-sample-run.mjs from two real runs of case txn 48213. Not hand-written.
// The trace and checkpoints come from a run with the forced bank timeout. The step timings come from a
// run without it. Re-run \`npm run sample:capture\` whenever the engine changes.

export type SampleSpan = { kind: "agent" | "llm" | "tool" | "retry" | "decision"; name: string; depth: number; start: number; ms: number; label: string };
export type SampleCheckpoint = { id: string; label: string; agent: string; hash: string; parent: string | null };

export const sampleRun = {
  runId: ${JSON.stringify(chaos.meta.id)},
  txn: "48213",
  totalMs: ${result(chaos).durationMs},
  trace: ${JSON.stringify(trace)} as SampleSpan[],
  checkpoints: ${JSON.stringify(checkpoints)} as SampleCheckpoint[],
  resumedFrom: ${JSON.stringify(resumedFrom)} as string | null,
  memoryLine: ${JSON.stringify(memoryLine)} as string | null,
};

export const sampleTimings = ${JSON.stringify(timings, null, 2)};
`;
fs.writeFileSync(out, body);
console.log(`Wrote ${out}: ${trace.length} spans, ${checkpoints.length} checkpoints, resumed from ${resumedFrom}.`);
